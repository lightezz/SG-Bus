export function getServiceMetadata(serviceNo: string): ServiceMetadata {
  if (SERVICE_METADATA_MAP[serviceNo]) {
    return SERVICE_METADATA_MAP[serviceNo];
  }
  // Deterministic fallback based on service number for authentic Singapore operator assignment
  const num = parseInt(serviceNo.replace(/\D/g, ''), 10) || 100;
  let operator: BusOperator = 'SBST';
  if (num >= 900 || (num >= 169 && num <= 190)) operator = 'SMRT';
  else if (num >= 800 && num < 900) operator = 'TTS';
  else if (num >= 350 && num < 400) operator = 'GAS';

  const hubs = ['City Terminus', 'Regional Hub', 'MRT Interchange', 'Town Centre Loop'];
  return {
    operator,
    origin: 'Origin Interchange',
    destination: hubs[num % hubs.length],
    frequency: '8–15 min',
  };
}
